def _draw_open_polyline_pdf(c, points: list[tuple[float, float]], dashed: bool = False) -> None:
    if len(points) < 2:
        return
    # Sets its own line width explicitly every call rather than trusting
    # whatever the canvas was last left at - it used to rely on a single
    # c.setLineWidth(0.5) set once before the whole multi-view loop, but
    # _add_dimensions_pdf (called after every view, in that same loop)
    # sets its own thinner dimension-line width and never restores it, so
    # every view after the first silently inherited the wrong (dimension)
    # width instead of the visible/hidden width it was supposed to have.
    # The 0.35/0.2mm values themselves also replace the old raw 0.5/0.3
    # *points* (~0.18mm/0.11mm) - too thin to read as a normal-weight
    # line at 1:1 print scale, which is the "light ink" look this fixes.
    from reportlab.lib.units import mm
    c.setLineWidth((_HIDDEN_LINE_WIDTH_MM if dashed else _VISIBLE_LINE_WIDTH_MM) * mm)
    c.setDash([2, 2] if dashed else [])
    p = c.beginPath()
    p.moveTo(*points[0])
    for pt in points[1:]:
        p.lineTo(*pt)
    c.drawPath(p, stroke=1, fill=0)
    c.setDash([])


def _draw_arrowhead_pdf(c, tip: tuple[float, float], direction_deg: float, size: float = 5.0) -> None:
    """Filled arrowhead in PAGE (point) coordinates, tip at `tip`, pointing
    along `direction_deg`."""
    import math
    a1 = math.radians(direction_deg + 150)
    a2 = math.radians(direction_deg - 150)
    p1 = (tip[0] + size * math.cos(a1), tip[1] + size * math.sin(a1))
    p2 = (tip[0] + size * math.cos(a2), tip[1] + size * math.sin(a2))
    path = c.beginPath()
    path.moveTo(*tip)
    path.lineTo(*p1)
    path.lineTo(*p2)
    path.close()
    c.drawPath(path, stroke=0, fill=1)


def _draw_horizontal_dim_pdf(c, to_page, x0: float, x1: float, y_measured: float, y_dim: float, text: str) -> None:
    """Horizontal dimension: extension lines up/down from (x0,y_measured)
    and (x1,y_measured) to the dimension line at y_dim, then the
    dimension line itself with arrowheads and centered text - all
    arguments in the view's local mm coordinates (offset already
    applied by the caller), converted to page points via `to_page`."""
    p0 = to_page((x0, y_measured))
    p1 = to_page((x1, y_measured))
    d0 = to_page((x0, y_dim))
    d1 = to_page((x1, y_dim))
    from reportlab.lib.units import mm
    c.setLineWidth(_DIM_LINE_WIDTH_MM * mm)
    c.line(p0[0], p0[1], d0[0], d0[1] + (6 if y_dim > y_measured else -6))
    c.line(p1[0], p1[1], d1[0], d1[1] + (6 if y_dim > y_measured else -6))
    c.line(d0[0], d0[1], d1[0], d1[1])
    _draw_arrowhead_pdf(c, d0, 0.0 if x1 > x0 else 180.0)
    _draw_arrowhead_pdf(c, d1, 180.0 if x1 > x0 else 0.0)
    c.setFont("Helvetica", 7)
    c.drawCentredString((d0[0] + d1[0]) / 2, d0[1] + 2, text)


def _draw_vertical_dim_pdf(c, to_page, y0: float, y1: float, x_measured: float, x_dim: float, text: str) -> None:
    """Vertical counterpart to _draw_horizontal_dim_pdf."""
    p0 = to_page((x_measured, y0))
    p1 = to_page((x_measured, y1))
    d0 = to_page((x_dim, y0))
    d1 = to_page((x_dim, y1))
    from reportlab.lib.units import mm
    c.setLineWidth(_DIM_LINE_WIDTH_MM * mm)
    c.line(p0[0], p0[1], d0[0] + (6 if x_dim > x_measured else -6), d0[1])
    c.line(p1[0], p1[1], d1[0] + (6 if x_dim > x_measured else -6), d1[1])
    c.line(d0[0], d0[1], d1[0], d1[1])
    _draw_arrowhead_pdf(c, d0, 90.0 if y1 > y0 else 270.0)
    _draw_arrowhead_pdf(c, d1, 270.0 if y1 > y0 else 90.0)
    c.saveState()
    c.setFont("Helvetica", 7)
    c.translate((d0[0] + d1[0]) / 2, (d0[1] + d1[1]) / 2)
    c.rotate(90)
    c.drawCentredString(0, 2, text)
    c.restoreState()


def _draw_diameter_leader_pdf(c, to_page, cx: float, cy: float, r: float, text: str, angle_deg: float = 45.0) -> None:
    """Leader line from a 45-degree point on the hole's actual measured
    edge out to a diameter callout - standard drafting convention for
    dimensioning a circular hole."""
    import math
    edge_local = (cx + r * math.cos(math.radians(angle_deg)), cy + r * math.sin(math.radians(angle_deg)))
    label_local = (cx + (r + 8) * math.cos(math.radians(angle_deg)), cy + (r + 8) * math.sin(math.radians(angle_deg)))
    edge_pt = to_page(edge_local)
    label_pt = to_page(label_local)
    from reportlab.lib.units import mm
    c.setLineWidth(_DIM_LINE_WIDTH_MM * mm)
    c.line(edge_pt[0], edge_pt[1], label_pt[0], label_pt[1])
    c.setFont("Helvetica", 7)
    c.drawString(label_pt[0] + 2, label_pt[1] - 2, text)



# Drawing scale for oversized parts. Everything up to this combined X+Y+Z size
# keeps the true 1:1 sheet it always had. Bigger parts (a 20 m road segment)
# would otherwise need a page far larger than a PDF viewer can open, so they
# are drawn at the first standard scale that fits and the title block, the
# dimension text and the SIZE line all report the real size.
_PDF_FULL_SIZE_LIMIT_MM = 1500.0
_PDF_TARGET_EXTENT_MM = 600.0
_PDF_STANDARD_SCALES = (2, 5, 10, 20, 50, 100, 200, 500, 1000)


def _scale_shape(shape, factor: float):
    """A uniformly scaled copy of a shape about the origin. Uses Shape.scale when this
    CadQuery has it, and the OCCT transform directly when it does not."""
    scale = getattr(shape, "scale", None)
    if callable(scale):
        return scale(factor)
    from OCP.BRepBuilderAPI import BRepBuilderAPI_Transform
    from OCP.gp import gp_Pnt, gp_Trsf

    trsf = gp_Trsf()
    trsf.SetScale(gp_Pnt(0, 0, 0), factor)
    return cq.Shape.cast(BRepBuilderAPI_Transform(shape.wrapped, trsf, True).Shape())


def pdf_scale_denominator(obj: "ShapeLike") -> int:
    """1 for anything up to _PDF_FULL_SIZE_LIMIT_MM, else the first standard
    scale denominator that brings the part's X+Y+Z extent under the target."""
    bb = _as_workplane(obj).val().BoundingBox()
    extent = bb.xlen + bb.ylen + bb.zlen
    if extent <= _PDF_FULL_SIZE_LIMIT_MM:
        return 1
    for n in _PDF_STANDARD_SCALES:
        if extent / n <= _PDF_TARGET_EXTENT_MM:
            return n
    return _PDF_STANDARD_SCALES[-1]


def _draw_center_mark_pdf(c, to_page, cx: float, cy: float, r: float) -> None:
    from reportlab.lib.units import mm

    c.saveState()
    c.setLineWidth(_DIM_LINE_WIDTH_MM * mm)
    c.setDash([6 * mm, 1.2 * mm, 1 * mm, 1.2 * mm], 0)
    for (ax, ay), (bx, by) in drawing_footer.center_mark(cx, cy, r):
        (x0, y0), (x1, y1) = to_page((ax, ay)), to_page((bx, by))
        c.line(x0, y0, x1, y1)
    c.restoreState()


def _draw_footer_pdf(c, prims, x0: float, y0: float) -> None:
    """Draw drawing_footer primitives (mm, y up) with their origin at page point (x0, y0)."""
    from reportlab.lib.units import mm

    c.saveState()
    c.setLineWidth(0.25 * mm)
    for p in prims:
        if p[0] == "line":
            c.line(x0 + p[1] * mm, y0 + p[2] * mm, x0 + p[3] * mm, y0 + p[4] * mm)
        else:
            _, x, y, size, bold, text = p
            c.setFont("Helvetica-Bold" if bold else "Helvetica", size * 2.835 * 0.95)
            c.drawString(x0 + x * mm, y0 + y * mm, text)
    c.restoreState()


def _add_dimensions_pdf(c, view: _View, offset: tuple[float, float], to_page, dim_mult: float = 1.0) -> None:
    """Real dimensions for one view: overall width (below), overall
    height (left), and one diameter callout per distinct hole size
    actually measured in the geometry (see _detect_circles /
    _distinct_hole_callouts - never from hole_diameter_mm or any other
    input parameter, for the same reason _part_size_mm reads geometry
    instead of plate_size/motor_size_mm)."""
    ox, oy = offset
    u_min, u_max, v_min, v_max = view.u_min + ox, view.u_max + ox, view.v_min + oy, view.v_max + oy

    # dim_mult is the drawing scale denominator: the view was drawn at 1/dim_mult
    # of real size, so printed values are multiplied back up to real size.
    _draw_horizontal_dim_pdf(c, to_page, u_min, u_max, v_min, v_min - 16, f"{view.width * dim_mult:.1f}")
    _draw_vertical_dim_pdf(c, to_page, v_min, v_max, u_min, u_min - 10, f"{view.height * dim_mult:.1f}")

    holes, groups = _hole_features(view)
    for hx, hy, hr in holes:
        _draw_center_mark_pdf(c, to_page, hx + ox, hy + oy, hr)
    for cx, cy, r, count, angle in groups:
        _draw_diameter_leader_pdf(c, to_page, cx + ox, cy + oy, r, drawing_footer.hole_label(2 * r * dim_mult, count), angle)


def _draw_view_pdf(c, view: _View, offset: tuple[float, float], to_page) -> None:
    ox, oy = offset
    for line in view.visible:
        pts = [to_page((x + ox, y + oy)) for x, y in line]
        _draw_open_polyline_pdf(c, pts, dashed=False)
    for line in view.hidden:
        pts = [to_page((x + ox, y + oy)) for x, y in line]
        _draw_open_polyline_pdf(c, pts, dashed=True)
    label_pt = to_page((view.u_min + ox, view.v_min + oy - _VIEW_LABEL_DROP))
    c.setFont("Helvetica-Bold", 8)
    c.drawString(label_pt[0], label_pt[1], view.label)


def export_pdf(
    obj: ShapeLike,
    path: Path,
    part_name: str = "PART",
    material: str | None = None,
    part_type: str | None = None,
    parts: list[tuple[str, ShapeLike]] | None = None,
    scale_den: int = 1,
    bom: dict | None = None,
    tolerance_class: str = "m",
) -> Path:
    """Multi-view orthographic PDF (front/top/side, HLR visible/hidden
    edges, title block), at true 1:1 scale unless `scale_den` is above 1 (see
    pdf_scale_denominator; only used for single oversized parts). If `parts` is given (assembly
    sub-parts, see assembly.get_assembly_parts), draws one such block per
    part, stacked on one sheet, instead of a single block for `obj`."""
    from reportlab.lib.units import mm
    from reportlab.pdfgen import canvas

    if parts:
        blocks = _stack_part_blocks(parts)
        all_offsets = [
            {name: (o[0], o[1] + y_shift) for name, o in offsets.items()}
            for _, _, offsets, y_shift in blocks
        ]
        overall_x0 = overall_y0 = float("inf")
        overall_x1 = overall_y1 = float("-inf")
        for (_, views, _, _), offsets in zip(blocks, all_offsets):
            x0, x1, y0, y1 = _combined_bbox(views, offsets, label_clearance=_LABEL_CLEARANCE, left_clearance=14.0)
            overall_x0, overall_x1 = min(overall_x0, x0), max(overall_x1, x1)
            overall_y0, overall_y1 = min(overall_y0, y0), max(overall_y1, y1)
        part_size_mm = None  # sheet holds multiple distinct parts - no single (X,Y,Z) to report
    else:
        wp = _as_workplane(obj)
        if scale_den > 1:
            wp = cq.Workplane(obj=_scale_shape(wp.val(), 1.0 / scale_den))
        views = _build_three_views(wp)
        offsets = _layout_three_views(views)
        blocks = [(part_name, views, offsets, 0.0)]
        all_offsets = [offsets]
        overall_x0, overall_x1, overall_y0, overall_y1 = _combined_bbox(
            views, offsets, label_clearance=_LABEL_CLEARANCE, left_clearance=14.0
        )
        part_size_mm = tuple(v * scale_den for v in _part_size_mm(views))

    drawing_w_mm = overall_x1 - overall_x0
    drawing_h_mm = overall_y1 - overall_y0

    margin = 20 * mm
    title_block_h = 28 * mm

    # Title block text is decided first so the sheet can be widened to fit
    # it - fixed column fractions made "SIZE: ... mm" run into the DATE cell.
    # SIZE is the real (X, Y, Z) size of the solid, read back off the HLR
    # views (_part_size_mm) - NOT drawing_w_mm/drawing_h_mm, which is the
    # SHEET's layout extent (three tiled views + gaps + title block).
    # Reporting the sheet extent here was the original bug: a 97mm plate's
    # title block claimed "257.5 x 122.5mm" because that's how much page
    # space three views + dimensions took up, not the part's real size.
    if part_size_mm:
        size_text = f"SIZE: {part_size_mm[0]:.1f} x {part_size_mm[1]:.1f} x {part_size_mm[2]:.1f} mm"
    else:
        size_text = "SIZE: n/a (multi-part sheet)"
    name_text = f"PART: {_clip(part_name.upper())}"
    type_text = f"TYPE: {_clip((part_type or 'n/a').upper())}"
    scale_text = f"SCALE: 1:{scale_den}"
    material_text = f"MATERIAL: {_clip(material or 'n/a')}"
    date_text = f"DATE: {_dt.date.today().isoformat()}"

    from reportlab.pdfbase.pdfmetrics import stringWidth

    pad = 10.0  # points, 5 either side of the text
    tb_needs = [
        max(stringWidth(name_text, "Helvetica-Bold", 10), stringWidth(type_text, "Helvetica", 8)) + pad,
        max(stringWidth(scale_text, "Helvetica", 8), stringWidth(size_text, "Helvetica", 8)) + pad,
        max(stringWidth(material_text, "Helvetica", 8), stringWidth(date_text, "Helvetica", 8)) + pad,
    ]
    footer_prims, footer_w_mm, footer_h_mm = drawing_footer.layout_footer(
        drawing_footer.build_footer(bom, tolerance_class, scale=f"1:{scale_den}"))
    footer_h = (footer_h_mm + 6.0) * mm            # notes, tolerance table and parts list sit under the title block
    page_w = max(drawing_w_mm * mm + 2 * margin, 150 * mm, sum(tb_needs) + 2 * margin, footer_w_mm * mm + 2 * margin)
    page_h = drawing_h_mm * mm + 2 * margin + title_block_h + footer_h

    path = _prepare_output_path(path)
    c = canvas.Canvas(str(path), pagesize=(page_w, page_h))

    origin_x = margin - overall_x0 * mm
    origin_y = margin + footer_h + title_block_h - overall_y0 * mm

    def to_page(pt: tuple[float, float]) -> tuple[float, float]:
        return (origin_x + pt[0] * mm, origin_y + pt[1] * mm)

    # No longer load-bearing - _draw_open_polyline_pdf now sets its own
    # width on every call - but kept as the sane default for the title
    # block's own border/divider lines drawn further down, which don't
    # go through that helper.
    c.setLineWidth(_VISIBLE_LINE_WIDTH_MM * mm)
    c.setStrokeColorRGB(0, 0, 0)

    for (label, block_views, _, y_shift), offsets in zip(blocks, all_offsets):
        if parts:
            top = next(v for v in block_views if v.name == "top")
            fx, _ = offsets["front"]
            label_pt = to_page((fx, offsets["top"][1] + top.v_max + 8))
            c.setFont("Helvetica-Bold", 10)
            c.drawString(label_pt[0], label_pt[1], label.upper())
        for view in block_views:
            _draw_view_pdf(c, view, offsets[view.name], to_page)
            _add_dimensions_pdf(c, view, offsets[view.name], to_page, dim_mult=scale_den)

    # Title block
    tb_x0, tb_y0 = margin, margin + footer_h
    tb_w = page_w - 2 * margin
    cols = _split_columns(tb_needs, tb_w)
    d1 = tb_x0 + cols[0]
    d2 = tb_x0 + cols[0] + cols[1]
    c.rect(tb_x0, tb_y0, tb_w, title_block_h, stroke=1, fill=0)
    c.line(tb_x0, tb_y0 + title_block_h / 2, tb_x0 + tb_w, tb_y0 + title_block_h / 2)
    c.line(d1, tb_y0, d1, tb_y0 + title_block_h)
    c.line(d2, tb_y0, d2, tb_y0 + title_block_h)

    c.setFont("Helvetica-Bold", 10)
    c.drawString(tb_x0 + 5, tb_y0 + title_block_h - 14, name_text)
    c.setFont("Helvetica", 8)
    c.drawString(tb_x0 + 5, tb_y0 + 8, type_text)
    c.drawString(d1 + 5, tb_y0 + title_block_h - 14, scale_text)
    c.drawString(d1 + 5, tb_y0 + 8, size_text)
    c.drawString(d2 + 5, tb_y0 + title_block_h - 14, material_text)
    c.drawString(d2 + 5, tb_y0 + 8, date_text)

    _draw_footer_pdf(c, footer_prims, margin, margin)

    c.showPage()
    c.save()
    return _assert_export_written(path, "PDF")


