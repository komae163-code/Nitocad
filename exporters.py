def _named_meshes(obj: ShapeLike, label: str, parts: list[tuple[str, ShapeLike]] | None, tolerance: float):
    import mesh_formats

    if parts:
        return [(name, *mesh_formats.mesh_from_shape(shape, tolerance)) for name, shape in parts]
    return [(label, *mesh_formats.mesh_from_shape(obj, tolerance))]


def export_glb(obj: ShapeLike, path: Path, label: str = "part", parts: list[tuple[str, ShapeLike]] | None = None) -> Path:
    import mesh_formats

    path = _prepare_output_path(path)
    mesh_formats.write_glb(path, _named_meshes(obj, label, parts, 0.05))
    return _assert_export_written(path, "GLB")


def export_3mf(obj: ShapeLike, path: Path, label: str = "part", parts: list[tuple[str, ShapeLike]] | None = None) -> Path:
    import mesh_formats

    path = _prepare_output_path(path)
    mesh_formats.write_3mf(path, _named_meshes(obj, label, parts, 0.05), title=label)
    return _assert_export_written(path, "3MF")


def export_urdf(obj: ShapeLike, path: Path, label: str = "part", material: str | None = None) -> Path:
    import materials
    import mesh_formats

    path = _prepare_output_path(path)
    verts, tris = mesh_formats.mesh_from_shape(obj, 0.1)
    mesh_formats.write_urdf_zip(path, label, verts, tris, density_g_cm3=materials.density_g_cm3(material), material=material)
    return _assert_export_written(path, "URDF")


def export_all(
    obj: ShapeLike,
    output_dir: Path,
    base_name: str,
    formats: list[str] | None = None,
    part_name: str | None = None,
    material: str | None = None,
    part_type: str | None = None,
    parts: list[tuple[str, ShapeLike]] | None = None,
    bom: dict | None = None,
    tolerance_class: str = "m",
    drawing_override: dict[str, Any] | None = None,
) -> dict[str, Path]:
    """Export `obj` to every format in `formats` (default: every format in
    DEFAULT_FORMATS - step, stl, iges, dxf, pdf). Returns
    {format: output_path}. Raises GenerationError on an unknown format or
    if any individual export fails - callers that want partial success on
    partial failure should call the individual export_* functions
    directly instead.

    `drawing_override`: {"dxf"|"pdf": callable(path)} replaces the generic drawing for that format
    (a building writes its own plan, elevation and section sheets).

    `bom`: the parts-list dict from assembly_checks.bill_of_materials; when given, dxf/pdf
    add a parts list. `tolerance_class` (f, m, c, v) sets the ISO 2768 general tolerance note.

    `parts`: optional list of (name, shape) for assembly sub-parts (see
    assembly.get_assembly_parts). Only affects dxf/pdf, which draw one
    multi-view block per part instead of one block for `obj`. step/stl/
    iges are unaffected and still export `obj` as-is - STEP already
    preserves named sub-parts via Assembly.save() (see cad_generator.py),
    and STL/IGES don't have a per-part drawing concept.
    """
    resolved_formats = validate_formats(list(formats) if formats else list(DEFAULT_FORMATS))
    if "urdf" in resolved_formats and parts:
        raise UnsupportedFormatError(
            "A URDF describes one rigid link, so it is not offered for assemblies. Export the parts one by one, "
            "or use STEP, GLB or 3MF for the whole assembly.")
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    label = part_name or base_name

    results: dict[str, Path] = {}
    for fmt in resolved_formats:
        out_path = output_dir / f"{base_name}.{_EXTENSION_BY_FORMAT[fmt]}"
        try:
            if fmt == "step":
                export_step(obj, out_path)
            elif fmt == "stl":
                export_stl(obj, out_path)
            elif fmt == "iges":
                export_iges(obj, out_path)
            elif fmt == "glb":
                export_glb(obj, out_path, label, parts)
            elif fmt == "3mf":
                export_3mf(obj, out_path, label, parts)
            elif fmt == "urdf":
                export_urdf(obj, out_path, label, material)
            elif fmt in ("dxf", "pdf") and drawing_override and fmt in drawing_override:
                drawing_override[fmt](out_path)  # e.g. a building's plans/elevations/sections
            elif fmt == "dxf":
                export_dxf(obj, out_path, part_name=label, material=material, part_type=part_type, parts=parts,
                           bom=bom, tolerance_class=tolerance_class)
            elif fmt == "pdf":
                export_pdf(
                    obj, out_path, part_name=label, material=material, part_type=part_type, parts=parts,
                    scale_den=1 if parts else pdf_scale_denominator(obj), bom=bom, tolerance_class=tolerance_class,
                )
        except GenerationError:
            raise
        except Exception as exc:  # noqa: BLE001 - cadquery/OCP/ezdxf/reportlab all raise different types
            raise GenerationError(f"{fmt.upper()} export failed: {exc}") from exc
        results[fmt] = out_path

    return results
