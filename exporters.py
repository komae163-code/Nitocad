def _prepare_output_path(path: Path) -> Path:
    """Create the destination directory and return a normalized Path."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def _assert_export_written(path: Path, fmt: str) -> Path:
    """Fail loudly if an exporter returns without producing a usable file."""
    if not path.is_file():
        raise GenerationError(f"{fmt.upper()} export did not create the expected file: {path}")
    if path.stat().st_size == 0:
        raise GenerationError(f"{fmt.upper()} export created an empty file: {path}")
    return path


# Set NITOCAD_STEP_ROUNDTRIP=0 to skip the re-import check (an emergency switch in
# case a particular OCCT build trips it on valid geometry). On by default.
def _roundtrip_enabled() -> bool:
    return os.environ.get("NITOCAD_STEP_ROUNDTRIP", "1").strip().lower() not in {"0", "false", "no", "off"}


def _shape_for_roundtrip_check(obj: ShapeLike):
    """The B-Rep that was actually written to the STEP file.

    A Workplane can hold several objects and the exporter writes all of them, so
    compare against their compound, not just `.val()` (the first one)."""
    if isinstance(obj, cq.Assembly):
        return obj.toCompound()
    if isinstance(obj, cq.Workplane):
        return obj.toCompound()
    return obj


def _exact_bounds(shape) -> tuple[float, float, float, float, float, float]:
    """Bounding box from the exact geometry, never from a mesh.

    cq's Shape.BoundingBox() lets OCCT use a triangulation when the shape has
    one. The source shape usually does (the STL export meshes it first) and the
    re-imported STEP never does, so the two boxes would differ by the mesh
    deflection and a perfectly good file would look broken."""
    from OCP.Bnd import Bnd_Box
    from OCP.BRepBndLib import BRepBndLib

    box = Bnd_Box()
    BRepBndLib.AddOptimal_s(shape.wrapped, box, False, False)
    xmin, ymin, zmin, xmax, ymax, zmax = box.Get()
    return xmin, ymin, zmin, xmax, ymax, zmax


def _validate_step_roundtrip(obj: ShapeLike, path: Path) -> None:
    """Re-import the STEP and check its bounding box and volume match the source.

    A geometric sanity check: it catches an empty, truncated, wrongly scaled or
    partly missing file. It does not prove metadata or assembly constraints
    survived. On failure the bad file is deleted so it can never be downloaded."""
    try:
        source = _shape_for_roundtrip_check(obj)
        imported = cq.importers.importStep(str(path)).val()
        src, imp = _exact_bounds(source), _exact_bounds(imported)
        scale = max(1.0, *(src[i + 3] - src[i] for i in range(3)), *(imp[i + 3] - imp[i] for i in range(3)))
        linear_tol = max(1e-4, scale * 1e-5)
        for axis, (expected, actual) in enumerate(zip(src, imp)):
            if abs(expected - actual) > linear_tol:
                raise GenerationError(
                    f"STEP round-trip changed bounding-box coordinate {axis}: "
                    f"source={expected:.9g}, imported={actual:.9g}, tolerance={linear_tol:.3g} mm"
                )
        source_volume = float(source.Volume())
        imported_volume = float(imported.Volume())
        if source_volume > 1e-9:
            volume_tol = max(1e-4, source_volume * 1e-5)
            if abs(source_volume - imported_volume) > volume_tol:
                raise GenerationError(
                    f"STEP round-trip changed volume: source={source_volume:.9g} mm^3, "
                    f"imported={imported_volume:.9g} mm^3, tolerance={volume_tol:.3g} mm^3"
                )
    except Exception as exc:
        try:
            path.unlink(missing_ok=True)
        except OSError:
            pass
        if isinstance(exc, GenerationError):
            raise
        raise GenerationError(f"STEP export could not be round-trip validated: {exc}") from exc


def export_step(obj: ShapeLike, path: Path) -> Path:
    """Export STEP, preserve assembly names, then verify geometry by reimport.

    A Workplane/Shape is exported through CadQuery's standard exporter. A
    CadQuery Assembly must use Assembly.export directly: flattening it to a
    compound first preserves geometry but discards component names and
    assembly structure in the STEP product tree.
    """
    path = _prepare_output_path(path)
    if isinstance(obj, cq.Assembly):
        assembly_export = getattr(obj, "export", None)
        if callable(assembly_export):
            assembly_export(str(path), exportType="STEP")
        else:  # compatibility with older CadQuery Assembly APIs
            obj.save(str(path), exportType="STEP")
    else:
        cq.exporters.export(_as_workplane(obj), str(path), exportType="STEP")
    _assert_export_written(path, "STEP")
    if _roundtrip_enabled():
        _validate_step_roundtrip(obj, path)
    return path


def export_stl(obj: ShapeLike, path: Path, tolerance: float = 0.1, angular_tolerance: float = 0.1) -> Path:
    if tolerance <= 0:
        raise ValueError("STL linear tolerance must be greater than zero")
    if angular_tolerance <= 0:
        raise ValueError("STL angular tolerance must be greater than zero")
    path = _prepare_output_path(path)
    cq.exporters.export(
        _as_workplane(obj),
        str(path),
        exportType="STL",
        tolerance=tolerance,
        angularTolerance=angular_tolerance,
    )
    return _assert_export_written(path, "STL")


# --------------------------------------------------------------------
# IGES - exact B-Rep, via OCP's IGESControl_Writer directly.
# --------------------------------------------------------------------

def export_iges(obj: ShapeLike, path: Path) -> Path:
    """Write an exact boundary-representation IGES file. Mirrors the
    standard OCCT STEPControl_Writer pattern cadquery already uses for
    STEP internally, just with IGESControl_Writer, and sets the IGES
    unit flag to millimeters to match every other export in this module
    (cadquery/CQ geometry is unitless-but-conventionally-mm; without
    this the reader on the other end may assume inches)."""
    from OCP.IGESControl import IGESControl_Controller, IGESControl_Writer
    from OCP.Interface import Interface_Static

    workplane = _as_workplane(obj)
    shape = workplane.val()
    occt_shape = shape.wrapped if hasattr(shape, "wrapped") else shape

    IGESControl_Controller.Init_s()
    Interface_Static.SetCVal_s("write.iges.unit", "MM")
    writer = IGESControl_Writer()
    writer.AddShape(occt_shape)
    writer.ComputeModel()

    path = _prepare_output_path(path)
    ok = writer.Write(str(path))
    if not ok:
        raise GenerationError(f"IGES export failed (OCP IGESControl_Writer.Write returned false) for {path}")
    return _assert_export_written(path, "IGES")


# --------------------------------------------------------------------
# Multi-view orthographic projection (front / top / side) - the shared
# geometry pipeline behind DXF and PDF export. Built on OCCT's HLRBRep
# hidden-line-removal algorithm via OCP: for a given viewing direction,
# it separates a solid's projected edges into visible (solid line) and
# hidden (dashed line) sets, which is the standard way to turn a 3D part
# into a real technical drawing rather than one flat cross-section.
# --------------------------------------------------------------------

@dataclass
class _View:
    """One projected view's geometry, already expressed in the view's own
    local 2D drawing coordinates (local-X, local-Y - see _VIEW_AXES)."""
    name: str
    label: str
    visible: list[list[tuple[float, float]]]
    hidden: list[list[tuple[float, float]]]
    u_min: float
    u_max: float
    v_min: float
    v_max: float
    # Only topology-confirmed internal cylindrical faces may produce
    # manufacturing-style diameter callouts. Empty means no proven holes.
    hole_circles: list[tuple[float, float, float]] = field(default_factory=list)

    @property
    def width(self) -> float:
        return self.u_max - self.u_min

    @property
    def height(self) -> float:
        return self.v_max - self.v_min


# view_name -> (looking_direction, local_horizontal_axis). Local vertical
# is looking_direction x horizontal_axis, so it isn't listed separately.
# Front and top are both defined with local-X = world +X, so a top view
# stacks directly above a front view with no extra horizontal
# registration needed. Front and side are both defined with local-Y =
# world +Z, so a side view sits directly beside a front view with no
# extra vertical registration needed. This is the standard trick that
# makes a 3-view layout line up automatically instead of needing each
# view manually re-aligned - see _layout_three_views.
_VIEW_AXES: dict[str, tuple["cq.Vector", "cq.Vector"]] = {
    "front": (cq.Vector(0, -1, 0), cq.Vector(1, 0, 0)),
    "top": (cq.Vector(0, 0, -1), cq.Vector(1, 0, 0)),
    "side": (cq.Vector(-1, 0, 0), cq.Vector(0, -1, 0)),
}

_VIEW_LABELS = {"front": "FRONT VIEW", "top": "TOP VIEW", "side": "RIGHT SIDE VIEW"}

# View labels sit BELOW the width-dimension line (which is drawn 16mm under
# the view, with extension lines running down to it). The old 6mm drop put
# every label right across those extension lines. _LABEL_CLEARANCE is the
# room callers must reserve under each view (passed to _combined_bbox) so
# the sheet/title block still clears the lowered label.
_VIEW_LABEL_DROP = 23.0
_LABEL_CLEARANCE = 26.0

# Orientation of each view's local axes was worked out algebraically
# against OCCT's HLRAlgo_Projector convention (gp_Ax2(origin, direction,
# x_dir), local-Y = direction x x_dir) rather than checked against a
# rendered drawing, since this sandbox has no network access to install
# cadquery's native OCCT dependencies (see the module docstring and
# tests/test_exporters.py). Visually confirm view orientation the first
# time this runs against real geometry.


def _edge_to_points(edge: "cq.Edge", curve_segments: int = 32) -> list[tuple[float, float]]:
    """Discretize one edge into 2D (x, y) points, dropping z. Valid both
    for the old section-plane use (z is constant, the cut height) and
    for HLR-projected edges (z is projection depth, unneeded once
    visible/hidden classification has already happened)."""
    if edge.geomType() == "LINE":
        pts = [edge.startPoint(), edge.endPoint()]
    else:
        ds = [i / (curve_segments - 1) for i in range(curve_segments)]
        pts = edge.positions(ds)
    return [(p.x, p.y) for p in pts]


def _hlr_edges(shape, direction: "cq.Vector", x_dir: "cq.Vector") -> tuple[list, list]:
    """Run OCCT's HLRBRep_Algo on `shape` for one viewing direction and
    return (visible_edges, hidden_edges) as lists of cq.Edge, in the
    view's local 2D frame - each edge's own X/Y already are the drawing
    coordinates (Z is projection depth)."""
    from OCP.HLRAlgo import HLRAlgo_Projector
    from OCP.HLRBRep import HLRBRep_Algo, HLRBRep_HLRToShape
    from OCP.gp import gp_Ax2, gp_Dir, gp_Pnt

    occt_shape = shape.wrapped if hasattr(shape, "wrapped") else shape

    ax2 = gp_Ax2(
        gp_Pnt(0, 0, 0),
        gp_Dir(direction.x, direction.y, direction.z),
        gp_Dir(x_dir.x, x_dir.y, x_dir.z),
    )
    algo = HLRBRep_Algo()
    algo.Add(occt_shape)
    algo.Projector(HLRAlgo_Projector(ax2))
    algo.Update()
    algo.Hide()

    to_shape = HLRBRep_HLRToShape(algo)

    def _collect(*compounds) -> list:
        out = []
        for comp in compounds:
            if comp is None or comp.IsNull():
                continue
            out.extend(cq.Shape.cast(comp).Edges())
        return out

    # VCompound/HCompound: visible/hidden sharp (C0) edges. Rg1Line*:
    # edges at smooth (tangent, G1) face joins, e.g. a fillet's silhouette
    # - without these a filleted edge's outline goes missing. OutLine*:
    # the true silhouette of a curved surface (e.g. a cylinder's apparent
    # edge), which only exists as an HLR construct, not a real model
    # edge. All three visible sets get one line style; same for hidden.
    visible = _collect(to_shape.VCompound(), to_shape.Rg1LineVCompound(), to_shape.OutLineVCompound())
    hidden = _collect(to_shape.HCompound(), to_shape.Rg1LineHCompound(), to_shape.OutLineHCompound())
    return visible, hidden


def _exact_projected_extents(shape, direction, x_dir):
    """Exact (u_min, u_max, v_min, v_max) of the solid's projection in a
    view's local frame, from the solid's true (non-tessellated) bounding
    box, or None if it can't be determined. Views are axis-aligned, so
    projecting the 8 corners of the exact axis-aligned box gives the exact
    extents. useTriangulation=False on purpose: STL export meshes the same
    shape earlier in export_all, and a mesh-based box can under-report
    curved parts. Any failure returns None, which leaves the extents
    derived from the HLR polylines exactly as before."""
    try:
        from OCP.Bnd import Bnd_Box
        from OCP.BRepBndLib import BRepBndLib

        occt_shape = shape.wrapped if hasattr(shape, "wrapped") else shape
        box = Bnd_Box()
        BRepBndLib.AddOptimal_s(occt_shape, box, False, False)
        if box.IsVoid():
            return None
        x0, y0, z0, x1, y1, z1 = box.Get()
        # view-local vertical axis = direction x x_dir (see _VIEW_AXES)
        vx = direction.y * x_dir.z - direction.z * x_dir.y
        vy = direction.z * x_dir.x - direction.x * x_dir.z
        vz = direction.x * x_dir.y - direction.y * x_dir.x
        us, vs = [], []
        for x in (x0, x1):
            for y in (y0, y1):
                for z in (z0, z1):
                    us.append(x * x_dir.x + y * x_dir.y + z * x_dir.z)
                    vs.append(x * vx + y * vy + z * vz)
        return min(us), max(us), min(vs), max(vs)
    except Exception:
        return None


def _snap_extent(poly_lo: float, poly_hi: float, exact_lo: float, exact_hi: float) -> tuple[float, float]:
    """HLR curves are discretized into polylines, so a circle's polyline
    bbox is slightly smaller than the circle (a 10mm cylinder measured
    9.97 / 9.99). Use the exact extents instead - but only when they agree
    with the drawn geometry: the exact box must contain the polyline box
    and exceed it by no more than 3% of the span. Anything else (a frame
    mismatch, a mesh-derived box) keeps the polyline values unchanged."""
    span = max(poly_hi - poly_lo, exact_hi - exact_lo)
    eps = 1e-6 + 1e-6 * span
    tol = 1e-6 + 0.03 * span
    contains = exact_lo <= poly_lo + eps and exact_hi >= poly_hi - eps
    close = (poly_lo - exact_lo) <= tol and (exact_hi - poly_hi) <= tol
    if contains and close:
        return round(exact_lo, 6), round(exact_hi, 6)
    return poly_lo, poly_hi


def _build_view(shape, name: str) -> _View:
    direction, x_dir = _VIEW_AXES[name]
    visible_edges, hidden_edges = _hlr_edges(shape, direction, x_dir)

    visible_polylines = [_edge_to_points(e) for e in visible_edges]
    hidden_polylines = [_edge_to_points(e) for e in hidden_edges]

    all_pts = [p for line in (visible_polylines + hidden_polylines) for p in line]
    if not all_pts:
        raise GenerationError(
            f"HLR projection produced no edges for the {name} view. "
            "The part may be empty or degenerate."
        )
    xs = [p[0] for p in all_pts]
    ys = [p[1] for p in all_pts]
    u_min, u_max, v_min, v_max = min(xs), max(xs), min(ys), max(ys)
    exact = _exact_projected_extents(shape, direction, x_dir)
    if exact is not None:
        u_min, u_max = _snap_extent(u_min, u_max, exact[0], exact[1])
        v_min, v_max = _snap_extent(v_min, v_max, exact[2], exact[3])
    return _View(
        name=name,
        label=_VIEW_LABELS[name],
        visible=visible_polylines,
        hidden=hidden_polylines,
        u_min=u_min,
        u_max=u_max,
        v_min=v_min,
        v_max=v_max,
        hole_circles=_detect_topology_holes(shape, name),
    )


def _build_three_views(workplane: "cq.Workplane") -> list[_View]:
    shape = workplane.val()
    return [_build_view(shape, name) for name in ("front", "top", "side")]


def _layout_three_views(views: list[_View], gap: float = 28.0) -> dict[str, tuple[float, float]]:
    """Return {view_name: (offset_x, offset_y)} to add to each view's raw
    local coordinates so front/top/side sit in the standard third-angle
    drafting arrangement: top view above the front view (shared X
    registration), right-side view beside the front view (shared Z
    registration), `gap` drawing units (mm) apart. Default bumped from
    the original 15mm to 28mm when dimensioning was added - each view
    now draws an overall-width dimension below it and an overall-height
    dimension to its left (_add_dimensions_dxf/_add_dimensions_pdf), and
    15mm wasn't reliably enough room for a dimension line + arrows +
    text to fit in the gap without touching the neighboring view.
    Estimated, not pixel-verified against a rendered drawing - see the
    module docstring's standing no-cadquery-install caveat."""
    by_name = {v.name: v for v in views}
    front, top, side = by_name["front"], by_name["top"], by_name["side"]

    offsets = {"front": (-front.u_min, -front.v_min)}

    # Placed edges: the front view is shifted by (-u_min, -v_min), so its
    # placed right/top edges are simply its width/height. (The old
    # "-front.u_min + front.width" added the shift twice, which inflated the
    # gap for origin-centered parts and, for parts sitting away from the
    # origin, could drop the side/top view on top of the front view.)
    front_top_edge_y = front.height
    offsets["top"] = (-front.u_min, front_top_edge_y + gap - top.v_min)

    front_right_edge_x = front.width
    offsets["side"] = (front_right_edge_x + gap - side.u_min, -front.v_min)

    return offsets


def _combined_bbox(
    views: list[_View],
    offsets: dict[str, tuple[float, float]],
    label_clearance: float = 6.0,
    left_clearance: float = 0.0,
) -> tuple[float, float, float, float]:
    """(min_x, max_x, min_y, max_y) across every view's geometry once
    placed, including room below each view for its label text and, when
    `label_clearance`/`left_clearance` are widened by the caller, the
    width/height DIMENSION lines that _add_dimensions_dxf/
    _add_dimensions_pdf draw below and to the left of each view - if
    this box doesn't account for that space, the title block (placed
    just below the returned box) ends up overlapping the dimension
    lines instead of sitting cleanly below everything, same failure
    mode as the "dimension leaders cut through the title block" defect
    flagged in the export QA pass this fix comes from."""
    xs: list[float] = []
    ys: list[float] = []
    for v in views:
        ox, oy = offsets[v.name]
        xs += [v.u_min + ox - left_clearance, v.u_max + ox]
        ys += [v.v_min + oy - label_clearance, v.v_max + oy]
    return min(xs), max(xs), min(ys), max(ys)


def _part_size_mm(views: list["_View"]) -> tuple[float, float, float]:
    """Real (X, Y, Z) size of the actual solid, derived from the HLR
    views themselves - NOT from any input parameter (plate_size,
    motor_size_mm, etc). Those describe what was *requested*; a
    template can auto-correct or reinterpret a parameter (e.g. the
    fillet-radius auto-correction, or motor_mount snapping motor_size_mm
    to the nearest NEMA face size) so what actually got built can differ
    from what was asked for. Reading the size back off the projected
    geometry is the only way the reported size can't silently diverge
    from the part - same principle as why the drawing itself is HLR-
    derived instead of hand-computed from parameters.

    front's local-X = world +X and local-Y(vertical) = world +Z; side's
    local-X = world +/-Y (see _VIEW_AXES) - so front.width is the X
    extent, side.width is the Y extent, and front.height (== side.height,
    barring a non-rectangular silhouette) is the Z extent.
    """
    by_name = {v.name: v for v in views}
    front, side = by_name["front"], by_name["side"]
    return (front.width, side.width, front.height)


def _hole_from_face(face, classifier, direction, x_dir, vertical):
    """If `face` is an internal cylindrical wall whose axis is parallel to the viewing
    direction, return its projected (center_x, center_y, radius), else None.

    "Internal" means a point just inside the cylinder (toward its axis) is OUTSIDE
    the owning solid, which separates a bore from an external shaft or boss."""
    from OCP.BRepAdaptor import BRepAdaptor_Surface
    from OCP.BRepTools import BRepTools
    from OCP.GeomAbs import GeomAbs_Cylinder
    from OCP.gp import gp_Pnt
    from OCP.TopAbs import TopAbs_OUT

    face_wrapped = face.wrapped if hasattr(face, "wrapped") else face
    surface = BRepAdaptor_Surface(face_wrapped)
    if surface.GetType() != GeomAbs_Cylinder:
        return None

    cylinder = surface.Cylinder()
    axis = cylinder.Axis()
    d = axis.Direction()
    axis_vec = (d.X(), d.Y(), d.Z())
    if abs(axis_vec[0] * direction.x + axis_vec[1] * direction.y + axis_vec[2] * direction.z) < 1.0 - 1e-6:
        return None  # not seen end-on in this view, so it does not project to a circle

    radius = float(cylinder.Radius())
    loc = axis.Location()
    a0 = (loc.X(), loc.Y(), loc.Z())
    u0, u1, v0, v1 = BRepTools.UVBounds_s(face_wrapped)
    point = surface.Value((u0 + u1) / 2.0, (v0 + v1) / 2.0)
    p = (point.X(), point.Y(), point.Z())
    axial = sum((p[i] - a0[i]) * axis_vec[i] for i in range(3))
    axis_point = tuple(a0[i] + axis_vec[i] * axial for i in range(3))
    radial = tuple(p[i] - axis_point[i] for i in range(3))
    radial_len = math.sqrt(sum(v * v for v in radial))
    if radial_len <= 1e-12 or radius <= 1e-9:
        return None

    eps = min(radius * 0.01, max(1e-7, min(1e-3, radius * 1e-4)))
    inward = max(radius - eps, radius * 0.5)
    sample = tuple(axis_point[i] + radial[i] / radial_len * inward for i in range(3))
    classifier.Perform(gp_Pnt(*sample), max(1e-7, eps * 0.1))
    if classifier.State() != TopAbs_OUT:
        return None

    # The axis is parallel to the view direction, so where along it a0 sits does not
    # change its 2D position.
    cx = a0[0] * x_dir.x + a0[1] * x_dir.y + a0[2] * x_dir.z
    cy = a0[0] * vertical.x + a0[1] * vertical.y + a0[2] * vertical.z
    return (cx, cy, radius)


def _detect_topology_holes(shape, view_name: str) -> list[tuple[float, float, float]]:
    """Return circular hole features proven by the source B-Rep topology.

    Only cylinders whose axis is parallel to the viewing direction project as
    circles in that view. If the OCCT topology query fails for a face it is skipped
    (and logged at debug); a face that cannot be classified never produces a
    callout, because an unverified manufacturing dimension is worse than a missing one.

    Returns projected (center_x, center_y, radius) candidates, de-duplicated."""
    try:
        from OCP.BRepClass3d import BRepClass3d_SolidClassifier

        direction, x_dir = _VIEW_AXES[view_name]
        vertical = direction.cross(x_dir)
        solids = shape.Solids() if hasattr(shape, "Solids") else []
        if not solids:
            solids = [shape]
    except Exception as exc:
        logger.debug("Topology-based hole recognition unavailable for %s view: %s", view_name, exc)
        return []

    found: list[tuple[float, float, float]] = []
    for solid in solids:
        try:
            classifier = BRepClass3d_SolidClassifier(solid.wrapped if hasattr(solid, "wrapped") else solid)
            faces = solid.Faces()
        except Exception as exc:
            logger.debug("Could not classify a solid for %s view holes: %s", view_name, exc)
            continue
        for face in faces:
            try:
                hole = _hole_from_face(face, classifier, direction, x_dir, vertical)
            except Exception as exc:
                logger.debug("Skipping a face during %s view hole detection: %s", view_name, exc)
                continue
            if hole is None:
                continue
            cx, cy, radius = hole
            if not any(math.hypot(cx - hx, cy - hy) <= 1e-4 and abs(radius - hr) <= 1e-4 for hx, hy, hr in found):
                found.append(hole)
    return found


def _validated_hole_circles(view: "_View") -> list[tuple[float, float, float]]:
    """Match visible projected loops to internal cylindrical faces in the B-Rep."""
    raw = _detect_circles(view)
    if not raw or not view.hole_circles:
        return []
    matched = []
    for cx, cy, radius in raw:
        for hx, hy, hr in view.hole_circles:
            center_tol = max(0.1, radius * 0.02)
            radius_tol = max(0.05, radius * 0.02)
            if math.hypot(cx - hx, cy - hy) <= center_tol and abs(radius - hr) <= radius_tol:
                matched.append((cx, cy, radius))
                break
    return matched


def _detect_circles(view: "_View", tolerance_frac: float = 0.02) -> list[tuple[float, float, float]]:
    """Detect internal circular loops suitable for tentative diameter callouts.

    HLR polylines do not retain face topology, so a closed circle alone is
    not proof of a hole: the outer rim of a cylinder is also circular.
    Reject circles that form the complete outer circular silhouette. Other
    loops are geometric candidates only, not guaranteed through-holes; do
    not treat these heuristic callouts as manufacturing-critical dimensions
    without topology-aware validation.

    Returns (center_x, center_y, radius) in the view's local coordinates.
    """
    circles: list[tuple[float, float, float]] = []
    span = max(view.width, view.height, 1.0)
    boundary_tol = max(0.05, 0.01 * span)
    for line in view.visible:
        if len(line) < 8:
            continue
        x0, y0 = line[0]
        x1, y1 = line[-1]
        if abs(x0 - x1) > 1e-3 or abs(y0 - y1) > 1e-3:
            continue
        pts = line[:-1]
        cx = sum(p[0] for p in pts) / len(pts)
        cy = sum(p[1] for p in pts) / len(pts)
        radii = [((p[0] - cx) ** 2 + (p[1] - cy) ** 2) ** 0.5 for p in pts]
        r_mean = sum(radii) / len(radii)
        if r_mean < 1e-6:
            continue
        max_dev = max(abs(r - r_mean) for r in radii)
        if max_dev / r_mean > tolerance_frac:
            continue

        # A loop matching all four view extrema is the outer silhouette
        # (e.g. the top view of a solid cylinder), not an internal hole.
        circle_bounds = (cx - r_mean, cx + r_mean, cy - r_mean, cy + r_mean)
        outer_silhouette = (
            abs(circle_bounds[0] - view.u_min) <= boundary_tol
            and abs(circle_bounds[1] - view.u_max) <= boundary_tol
            and abs(circle_bounds[2] - view.v_min) <= boundary_tol
            and abs(circle_bounds[3] - view.v_max) <= boundary_tol
        )
        if not outer_silhouette:
            circles.append((cx, cy, r_mean))
    return circles


def _distinct_hole_callouts(circles: list[tuple[float, float, float]], group_tol: float = 0.05) -> list[tuple[float, float, float]]:
    """Collapse detected circles into one representative circle per
    distinct real diameter (grouped within `group_tol` mm of radius), so
    a plate with 4 identical corner holes gets one callout, not four -
    matching normal drafting convention of dimensioning one instance of
    a repeated feature."""
    groups: list[list[tuple[float, float, float]]] = []
    for c in sorted(circles, key=lambda c: c[2]):
        placed = False
        for g in groups:
            if abs(g[0][2] - c[2]) <= group_tol:
                g.append(c)
                placed = True
                break
        if not placed:
            groups.append([c])
    return [g[0] for g in groups]


def _hole_features(view: "_View") -> tuple[list[tuple[float, float, float]], list[tuple[float, float, float, int, float]]]:
    """(every distinct proven hole, one entry per diameter with its count).

    Identical circles from stacked parts that share an axis count once. The groups are what
    gets dimensioned ("4X \u00d85"), the full list is what gets centre marks."""
    unique: list[tuple[float, float, float]] = []
    for cx, cy, r in _validated_hole_circles(view):
        if not any(math.hypot(cx - ux, cy - uy) <= 1e-3 and abs(r - ur) <= 1e-3 for ux, uy, ur in unique):
            unique.append((cx, cy, r))
    bounds = (view.u_min, view.u_max, view.v_min, view.v_max)
    groups = [
        (cx, cy, r, count, drawing_footer.leader_angle(cx, cy, r, unique, bounds))
        for cx, cy, r, count in sorted(drawing_footer.hole_groups(unique), key=lambda g: g[2])
    ]
    return unique, groups


def _build_part_block(obj: "ShapeLike") -> tuple[list[_View], dict[str, tuple[float, float]]]:
    workplane = _as_workplane(obj)
    views = _build_three_views(workplane)
    offsets = _layout_three_views(views)
    return views, offsets


def _stack_part_blocks(
    parts: list[tuple[str, "ShapeLike"]],
    block_gap: float = 40.0,
    label_clearance: float = _LABEL_CLEARANCE,
    left_clearance: float = 14.0,
) -> list[tuple[str, list[_View], dict[str, tuple[float, float]], float]]:
    """Lay out one front/top/side block per part, stacked vertically down
    the page. Each part keeps its own internal `_layout_three_views`
    registration; this only adds a per-block Y shift so blocks don't
    overlap. Returns (part_label, views, offsets, y_shift) tuples - the
    y_shift is added on top of each view's own offset when drawing.

    label_clearance/left_clearance default to the same 20.0/14.0 every
    export_dxf/export_pdf caller passes to _combined_bbox for the actual
    sheet extent - this function's own internal _combined_bbox call has
    to match those, or the vertical space it reserves per block
    (block_height, below) under-counts the room each view's width
    dimension line actually needs (drawn ~16mm below the view - see
    _add_dimensions_dxf/_add_dimensions_pdf - vs. the 6.0 the old
    default-args call reserved for it), the same "reserved box doesn't
    match what's actually drawn" defect _combined_bbox's own docstring
    already warns about for the single-part case. Currently masked by
    the generous fixed block_gap=40.0 rather than visible as an actual
    overlap, but not something to leave to that margin alone."""
    blocks: list[tuple[str, list[_View], dict[str, tuple[float, float]], float]] = []
    cursor_y = 0.0
    for name, shape in parts:
        views, offsets = _build_part_block(shape)
        _, _, y_min, y_max = _combined_bbox(
            views, offsets, label_clearance=label_clearance, left_clearance=left_clearance
        )
        block_height = y_max - y_min
        y_shift = cursor_y - y_min
        blocks.append((name, views, offsets, y_shift))
        cursor_y += block_height + block_gap
    return blocks



