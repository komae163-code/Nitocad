"""
Multi-format export pipeline for generated CAD geometry.

cad_generator.py previously hardcoded exactly two output formats (STEP
via cq.exporters, STL via cq.exporters). This module generalizes that
into a real Tier-1 export matrix:

    step  - exact B-Rep solid, mechanical CAD interchange (SolidWorks,
            Fusion 360, CATIA), CNC milling/turning, injection molding.
            Uses cq.exporters (STEPControl_Writer under the hood).
    stl   - triangulated mesh, additive manufacturing (FDM/SLA/SLS) and
            the in-browser three.js preview. Uses cq.exporters.
    iges  - exact B-Rep solid, legacy mechanical interchange. cadquery's
            own exporters module (2.3.1) doesn't expose an IGES
            ExportType - only STEPControl_Writer is wired up - so this
            calls OCP's IGESControl_Writer directly. That's not a new
            dependency: OCP is the OCCT binding cadquery is already
            built on, so this uses the same kernel STEP export uses.
    dxf   - true multi-view orthographic drawing (front/top/side), each
            view built via OCCT's HLR (hidden-line-removal) algorithm,
            for laser/plasma/waterjet cutting and full technical
            drawings - not a placeholder, not a single cross-section.
    pdf   - 1:1 scale vector engineering drawing with the same
            front/top/side views, a title block, and per-view labels,
            for shop-floor printing and dimensional inspection.
    glb   - binary glTF 2.0 for web viewers, AR and game engines.
    3mf   - 3D Manufacturing Format for slicers and print services.
    urdf  - a zip with one rigid-link URDF, its STL mesh and a README,
            for ROS and simulators. Single parts only.
    (glb, 3mf and urdf are written by mesh_formats.py from OCCT's own
    tessellation, in pure Python, so no mesh library is added. They are
    not in DEFAULT_FORMATS: ask for them by name.)

Scope notes (read before assuming more than what's here):

  * DXF/PDF are a real multi-view orthographic projection: front, top,
    and right-side views, each generated via OCCT's HLRBRep_Algo hidden-
    line-removal algorithm (through OCP, the same OCCT binding cadquery
    itself is built on - no new dependency), which separates each view's
    edges into visible (solid line) and hidden (dashed line) sets. This
    replaced the old single-horizontal-section approach (`Workplane.
    section()` at Z=0), which only captured geometry that happened to
    intersect one cutting plane - a stepped shaft's diameter change
    along its axis, for example, was invisible to it. There is no
    `multi_view`/`view_mode` flag; this is simply what `export_dxf` and
    `export_pdf` do now, for every part.
  * Assemblies get a *multi-part* drawing on top of that: `export_all`
    accepts a `parts` list (see assembly.get_assembly_parts) and, when
    given one, lays out one full front/top/side block per sub-part
    (each individually labeled) instead of a single block for the
    merged compound. This is a separate axis from multi-view - a
    single-part export always uses multi-view; a multi-part export uses
    multi-view *per part*, stacked on one sheet.
  * DXF layers are VISIBLE / HIDDEN / LABELS / BORDER, one drawing-line
    classification that applies to any part geometry, replacing the old
    PIECE_OUTLINE / HOLES / CENTERLINES set derived from section-wire
    nesting (which doesn't generalize to HLR edges - HLR doesn't produce
    closed hole wires, it produces visible/hidden edge segments).
  * GLB, 3MF and URDF are built in mesh_formats.py from the shape's
    tessellation. They were added after the notes above, with tests that
    read the files back (tests/test_mesh_formats.py). Opening them in a
    real viewer, slicer and simulator is still worth doing once per release.
  * This module was written and reviewed against the cadquery 2.3.1 /
    OCP API surface pinned in requirements.txt, but could not be
    executed against real OCCT geometry in the sandbox this was
    authored in (no network access to install cadquery's native
    dependencies). Run `pytest tests/test_exporters.py` in an
    environment with the project's actual dependencies installed
    (the existing Dockerfile/CI already has them) before shipping.
"""
